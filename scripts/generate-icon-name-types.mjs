import { readdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const iconsDir = resolve('app/assets/icons')
const outFile = resolve('app/types/components/app/icon.ts')

// 1. Читаем все файлы из папки иконок
const files = readdirSync(iconsDir)
  .filter(name => name.endsWith('.svg'))
  .sort()

// 2. Обрезаем .svg → получаем чистые имена
const names = files.map(name => name.replace(/\.svg$/, ''))

// 3. Собираем содержимое TS-файла
const content = `// AUTOGENERATED FILE. DO NOT EDIT.

export const iconNames = [
${names.map(n => `  '${n}',`).join('\n')}
] as const

export type IconName = (typeof iconNames)[number]
`

// 4. Пишем файл
writeFileSync(outFile, content, 'utf8')
